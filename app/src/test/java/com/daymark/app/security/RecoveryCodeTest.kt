import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.security.SecureRandom

/**
 * The Kotlin recovery code is the same code the Companion prints, and these are the vectors that
 * say so.
 *
 * ## Why fixed vectors and not "read both files carefully"
 *
 * `companion/web/src/lib/recovery/recoveryCode.ts` and `RecoveryCode.kt` are two implementations of
 * one alphabet and one weighted checksum. Two implementations that have merely been compared by eye
 * are two implementations: a transposed pair of symbols in the alphabet, an off-by-one in the
 * position weights, an `uppercase()` applied before rather than after separators are stripped — none
 * of those is visible in a diff between two languages, and every one of them produces codes that
 * look exactly right and open nothing.
 *
 * So the vectors below were GENERATED by running the TypeScript module under vitest and pasted here
 * verbatim. The generator is not committed — it was twenty lines importing `checkSymbol`,
 * `normalizeRecoveryInput` and `formatRecoveryCode` and printing their output for a
 * deterministically-seeded set of payloads. If these ever need regenerating, that is the recipe:
 * the values here must come from the TypeScript, never from this file's own arithmetic, or the
 * parity claim is circular and proves nothing.
 *
 * ## What parity does and does not mean here
 *
 * The two codes are different LENGTHS on purpose (20 payload symbols here, 29 there; the header of
 * `RecoveryCode.kt` says why), so no vector below is a whole Companion code. What is pinned is
 * everything that is length-independent and would silently diverge: the alphabet and its ORDER, the
 * check symbol's arithmetic over a payload of any length, and exactly what canonicalisation strips
 * and folds.
 */
class RecoveryCodeTest {

    // ─── Vectors generated by the TypeScript module ────────────────────────────────────────────

    /** `RECOVERY_ALPHABET` as the TypeScript prints it. The ORDER is the arithmetic. */
    private val tsAlphabet = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"

    /**
     * `payload -> checkSymbol(payload)` over 20-symbol payloads, from the TypeScript. The last four
     * are edge payloads: every symbol the first, every symbol the last, and the alphabet walked in
     * order from each end.
     */
    private val checkVectors: List<Pair<String, Char>> = listOf(
