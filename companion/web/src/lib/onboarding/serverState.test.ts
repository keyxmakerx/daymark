/**
 * Every authored string the module can emit, over an exhaustive matrix of inputs.
 *
 * Generated rather than listed. A constant that only appears on an odd combination of responses is
 * exactly the one a hand-written list forgets, and it is exactly the one written in a hurry.
 */
function corpus(): { where: string; text: string }[] {
  const shapes: Record<string, ProbeResponse> = {
    ok: OK_TRUE,
    refused: OK_FALSE_503,
    smtpOn: CONFIG_ON,
    smtpOff: CONFIG_OFF,
    gone: GONE,
    proxy: PROXY_PAGE,
    teapot: { kind: 'response', status: 418, body: '{"error":"sync API not configured"}' },
  }
  const out: { where: string; text: string }[] = []
  for (const [i, s] of STANDING_STRINGS.entries()) out.push({ where: `standing[${i}]`, text: s })

  for (const protocol of ['https:', 'http:', 'file:', '']) {
    out.push(
      ...authoredStrings(read(protocol, null)).map((text) => ({ where: `${protocol} null`, text })),
    )
    for (const [an, a] of Object.entries(shapes)) {
      for (const [bn, b] of Object.entries(shapes)) {
        for (const [cn, c] of Object.entries(shapes)) {
          const reading = read(protocol, { liveness: a, writability: b, capability: c })
          const where = `${protocol} ${an}/${bn}/${cn} → ${reading.id}`
          out.push(...authoredStrings(reading).map((text) => ({ where, text })))
        }
      }
    }
  }
  return out
}

describe('the disclosure rule holds over everything this module can say', () => {
  const all = corpus()

  it('the corpus is real, and covers every state', () => {
    // Non-vacuity, first. Without this the scan below could pass on an empty list forever.
    expect(all.length).toBeGreaterThan(2_000)
    const joined = all.map((e) => e.text).join('\n')
    // Sentences the module really ships. If the copy is rewritten these should be updated
    // deliberately; if the corpus collector broke, they vanish and this fails.
    expect(joined).toContain('carries no reason')
    expect(joined).toContain('Nothing on this screen contradicts a working setup')
    expect(joined).toContain('opened from a file on this device')
    expect(joined).toContain('DAYMARK_DATA_DIR')
    expect(joined).toContain('DAYMARK_AUTH_TOKEN')
    expect(joined).toContain('DAYMARK_BASE_PATH')
    // And every state's word really did make it in.
    for (const id of [
      'page-not-served',
      'not-checked',
      'no-answer',
      'partial-answer',
      'not-ready',
      'undocumented-answer',
      'answering',
    ] as ServerStateId[]) {
      const word = read(id === 'page-not-served' ? 'file:' : 'https:', null).word
      expect(word.length).toBeGreaterThan(0)
    }
    expect(joined).toContain('Answering')
    expect(joined).toContain('Not ready')
  })

  it('every detector fires on the sentence it exists to catch', () => {
    // The half that makes the next test mean something. Each `fires` string is a plausible,
    // well-intentioned sentence that this page must never contain.
    for (const w of WITHHELD) {
      expect(w.re.test(w.fires), `${w.id}: detector does not fire on its own example`).toBe(true)
    }
    // …and they are not "match everything" regexes: an ordinary sentence from the module passes.
    for (const w of WITHHELD) {
      expect(w.re.test('The process is up and routing requests.'), `${w.id}: over-broad`).toBe(false)
    }
  })

  it('names nothing that is withheld, in any state, for any combination of responses', () => {
    const hits: string[] = []
    for (const { where, text } of all) {
      for (const w of WITHHELD) {
        const m = w.re.exec(text)
        if (m) hits.push(`${w.id} — "${m[0]}" in ${where}: ${text.slice(0, 120)}`)
      }
    }
    expect(hits).toEqual([])
  })

  it('the fixed panel copy is in the scan too', () => {
    expect(STANDING_STRINGS).toContain(PANEL_LEDE)
    expect(STANDING_STRINGS).toContain(PANEL_FOOTER)
    expect(STANDING_STRINGS).toContain(SYNC_NOT_PROBED)
    expect(STANDING_STRINGS).toContain(BUSY_WORD)
    // The lede bounds what a reader may expect before they read a single row.
    expect(PANEL_LEDE).toContain('It is not a check of your setup')
    expect(PANEL_FOOTER).toContain('Every request behind this panel was unauthenticated')
  })
})

describe('bytes the module did not author are confined to one field', () => {
  it('keeps a hostile response body and error string out of every authored string', () => {
    // The containment proof, and the strongest evidence the scan above has teeth. Every withheld
    // subject at once, arriving from the wire. If authored copy and machine bytes were ever merged
    // into one field, these words would surface in `authoredStrings` and this fails loudly.
    const poison =
      'DAYMARK_TRUSTED_PROXIES= unset shared bucket lockout /data 65532 chown disk full ' +
      'permission denied DAYMARK_SMTP_HOST=mail.example.org password secret 3 therapist ' +
      'relationships owner healthy secure ✅ 67% score'
    const probes: ProbeSet = {
      liveness: { kind: 'transport', error: poison },
      writability: { kind: 'response', status: 500, body: poison },
      capability: { kind: 'response', status: 500, body: poison },
    }
    const r = read('https:', probes)

    // Presence half: the poison really did arrive, and really is on the page somewhere.
    const details = r.probes.map((p) => p.detail).filter((d): d is string => d !== null)
    expect(details).toHaveLength(3)
    expect(details.join(' ')).toContain('DAYMARK_TRUSTED_PROXIES')
    expect(details.join(' ')).toContain('65532')

    // Absence half: and it is confined to `detail`, which the corpus scan excludes by design —
    // these are bytes the caller already received from the origin that served this page, quoted
    // rather than paraphrased, and never blended into the module's own vocabulary.
    for (const text of authoredStrings(r)) {
      for (const w of WITHHELD) {
        expect(w.re.test(text), `${w.id} leaked into an authored string: ${text}`).toBe(false)
      }
    }
  })

  it('caps what it quotes, so an upstream page cannot take over the panel', () => {
    const huge = 'DAYMARK_TRUSTED_PROXIES '.repeat(500)
    const l = readProbeLine('liveness', { kind: 'response', status: 500, body: huge })
    expect(l.detail!.length).toBeLessThan(DETAIL_LIMIT + 40)
  })
})
